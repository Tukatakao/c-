//控制流简介
/*
程序运行时，CPU会从main()的顶部开始执行语句（默认情况下按顺序执行）。实际执行的语句序列称为程序的执行路径。

但是如果需要分支 那么在普通顺序执行的程序中是不可能的
所以需要语句来控制程序执行路径
控制流语句：
1.条件   if else switch
2.跳转  goto break continue
3.函数调用    function calls return
4.循环       while do-while for ranged-for
5.停止      std::exit() std::abort()
6.异常      try throw catch






*/