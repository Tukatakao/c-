//If语句与代码块
/*
条件语句会根据某个判断条件，决定是否执行相关语句。

1.if语句
if (条件表达式)  
   语句;

或者

if(条件表达式)
    true_对应的语句;
else
    false_对应的语句;
但是如果语句是多条 要用代码块包起来



条件结果对应的单条语句是否应该放在代码块中？
考虑将与if或else相关的单条语句放在代码块中（特别是在学习阶段）。
如果一直使用代码块 会使得代码垂直间距增大，降低可读性
但是学习阶段使用 



隐式块：
如果没有在if else语句中显式使用代码块，编译器会隐式创建代码块。
就是单句语句 其实也相当于有代码块。

但是不要使用在单个语句或者代码块中定义的变量！
因为代码块结束会销毁！


*/